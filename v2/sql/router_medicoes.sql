-- SULSIGN OS 2.0 — TEMPO DE ROUTER (mod_rtr.js)
-- Rodar no SQL Editor do Supabase (obeamqkcuytctfczhook). Idempotente.
-- router_medicoes: cada medição (m.l., tempo, chapas) vinculada à OS.
-- router_config:   parâmetros compartilhados (presets de material,
--                  máquina e cobrança), uma linha por chave.
-- Padrão do projeto: RLS só para authenticated, soft-delete em
-- deletado_em, updated_at pela trigger ss20_touch_updated_at().
-- ═══════════════════════════════════════════════════════════════

create table if not exists router_medicoes (
  id                bigint generated by default as identity primary key,
  os_id             uuid references ordens_servico(id) on delete set null,
  job               text,                        -- SS-AAAA_MM-## ou rótulo do job/evento
  titulo            text,                        -- arquivos medidos
  arquivos          jsonb default '[]'::jsonb,   -- [{nome, formato, qtd, chapas, ml, maquina_min, camadas:[{camada, preset, op, n, ml, passadas, tempo_min}]}]
  ml                numeric,                     -- metros lineares de corte (cobráveis)
  tempo_maquina_min numeric,                     -- corte + mergulho + vazio + trocas
  tempo_total_min   numeric,                     -- máquina + setup de chapa + programação
  chapas            integer,
  area_pecas_m2     numeric,
  valor_ml          numeric,                     -- R$/m.l. usado no cálculo
  valor_router      numeric,                     -- ml × valor_ml
  params            jsonb,                       -- snapshot de máquina/cobrança/presets usados
  tempo_real_min    numeric,                     -- apontado depois, calibra o fator dos presets
  obs               text,
  criado_por        text,
  created_at        timestamptz default now(),
  updated_at        timestamptz default now(),
  deletado_em       timestamptz
);
create index if not exists idx_rtr_med_os  on router_medicoes(os_id);
create index if not exists idx_rtr_med_job on router_medicoes(job);
create index if not exists idx_rtr_med_del on router_medicoes(deletado_em);

alter table router_medicoes enable row level security;
drop policy if exists router_medicoes_auth on router_medicoes;
create policy router_medicoes_auth on router_medicoes
  for all to authenticated using (true) with check (true);

drop trigger if exists trg_rtr_med_touch on router_medicoes;
create trigger trg_rtr_med_touch
  before update on router_medicoes
  for each row execute function ss20_touch_updated_at();

create table if not exists router_config (
  chave      text primary key,                   -- 'parametros'
  valor      jsonb not null default '{}'::jsonb, -- {presets:{id:{...}}, maq:{...}, cob:{...}}
  updated_at timestamptz default now()
);
alter table router_config enable row level security;
drop policy if exists router_config_auth on router_config;
create policy router_config_auth on router_config
  for all to authenticated using (true) with check (true);
